const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const { examples, compileRequest, compilationResult, compilerExplorerUrl, assemblyFindings } = require("../src/utils/cpp-examples")

test("every compiler panel follows a complete C++ program and has a known configuration", () => {
  const article = fs.readFileSync("src/pages/2026-10-30-threads-mutexes-atomics/index.md", "utf8")
  const pairs = [...article.matchAll(/```cpp\n([\s\S]*?)```\s*<div data-cpp-example="([^"]+)"/g)]
  assert.equal(pairs.length, 8)
  pairs.forEach(([, code, id]) => { assert.ok(examples[id]); assert.match(code, /int main\(/); assert.match(code, /std::cout/) })
  assert.equal(examples["data-race"].run, false)
  assert.equal(examples["recursive-lock"].run, false)
})
test("Compiler Explorer requests use C++20 and distinguish compiling from running", () => {
  const asm = compileRequest("int main() {}", "-O2", false)
  assert.equal(asm.options.filters.execute, false)
  assert.equal(asm.allowStoreCodeDebug, false)
  const run = compileRequest("int main() {}", "-O0", true)
  assert.equal(run.options.filters.execute, true)
  assert.match(run.options.userArguments, /-std=c\+\+20 -O0 -pthread -latomic/)
})
test("compile errors, link errors, timeouts and runtime failures cannot appear as successful runs", () => {
  const failed = compilationResult({ code: 1, stderr: [{ text: "\u001b[31merror\u001b[0m" }], asm: [{ text: "<Compilation failed>" }] }, false)
  assert.equal(failed.diagnostics, "error")
  assert.equal(failed.assembly, "")
  assert.equal(compilationResult({ code: 1, stderr: [{ text: "syntax error" }] }, true).success, false)
  const link = compilationResult({ code: 0, execResult: { didExecute: false, buildResult: { stderr: [{ text: "undefined reference" }] } } }, true)
  assert.equal(link.success, false)
  assert.match(link.diagnostics, /undefined reference/)
  const timedOut = compilationResult({ code: 0, execResult: { didExecute: true, code: 0, timedOut: true } }, true)
  assert.equal(timedOut.success, false)
  assert.equal(timedOut.status, "Execution timed out")
  assert.equal(compilationResult({ code: 0, execResult: { didExecute: true, code: 1 } }, true).success, false)
  const result = compilationResult({ code: 0, asm: [{ text: "ret" }], execResult: { didExecute: true, code: 0, stdout: [{ text: "42" }] } }, true)
  assert.equal(result.success, true)
  assert.equal(result.output, "42")
  assert.equal(result.assembly, "ret")
})
test("Compiler Explorer links preserve source and compiler settings without auto-execution", () => {
  const source = '// café → output\nint main() {}'
  const url = compilerExplorerUrl(source, "g142", "-O2")
  const data = JSON.parse(atob(decodeURIComponent(url.split('/clientstate/')[1])))
  assert.equal(data.sessions[0].source, source)
  assert.equal(data.sessions[0].compilers[0].id, "g142")
  assert.equal(data.sessions[0].executors, undefined)
})
test("instruction observations come from assembly, not assumptions about the example", () => {
  assert.deepEqual(assemblyFindings("mov eax, 42\nret"), [])
  assert.equal(assemblyFindings("lock add DWORD PTR [rip], 1").length, 1)
  assert.equal(assemblyFindings("lock cmpxchg QWORD PTR [rip], rdx").length, 1)
})
